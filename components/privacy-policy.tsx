/**
 * מדיניות פרטיות של חנות (חובת היידוע, סעיף 11 לחוק הגנת הפרטיות, כפי שתוקן בתיקון 13).
 * הנוסח נבנה מפרטי המשתלה ומהמודולים הפעילים בה. הנחת עבודה (החלטת בעלים, 2026-11-16): בחנויות יופעלו
 * Google Analytics, פיקסל של Meta ועוגיות, ולכן הם מתוארים גם לפני שהם מוטמעים בפועל.
 * הנוסח אינו ייעוץ משפטי ויש להעביר אותו לבדיקת עורך דין.
 */
export const PRIVACY_UPDATED_AT = '2026-11-16';

const dateFmt = new Intl.DateTimeFormat('he-IL', { dateStyle: 'long', timeZone: 'Asia/Jerusalem' });

export interface PrivacyPolicyProps {
  name: string;
  email?: string | null;
  phone?: string | null;
  address?: string | null;
  /** חשבונות לקוח פעילים: אזור אישי, כתובות, מועדפים, יצוא ומחיקה עצמית */
  customerAccounts: boolean;
  /** מועדון לקוחות: צבירת נקודות */
  loyalty: boolean;
  /** טופס הרשמה לדיוור */
  newsletter: boolean;
  /** משלוח עד הבית */
  delivery: boolean;
}

function H2({ children }: { children: React.ReactNode }) {
  return <h2 className="mt-8 text-xl font-bold text-gray-900">{children}</h2>;
}

function List({ children }: { children: React.ReactNode }) {
  return <ul className="mt-2 list-disc space-y-1 pr-6">{children}</ul>;
}

export function PrivacyPolicy(p: PrivacyPolicyProps) {
  const contact = [p.email && `בדואר אלקטרוני: ${p.email}`, p.phone && `בטלפון: ${p.phone}`, p.address && `בכתובת: ${p.address}`].filter(
    (c): c is string => Boolean(c),
  );
  return (
    <article dir="rtl" className="mx-auto max-w-3xl px-6 py-12 leading-relaxed text-gray-700">
      <h1 className="text-3xl font-bold tracking-tight text-gray-900">מדיניות פרטיות</h1>
      <p className="mt-2 text-sm text-gray-600">עודכנה לאחרונה: {dateFmt.format(new Date(PRIVACY_UPDATED_AT))}</p>
      <p className="mt-4">
        {p.name} (&quot;המשתלה&quot;, &quot;אנחנו&quot;) מכבדת את פרטיותכם. במסמך הזה מוסבר איזה מידע נאסף באתר, למה, למי הוא
        מועבר, כמה זמן הוא נשמר ואילו זכויות יש לכם. המדיניות נכתבה לפי חוק הגנת הפרטיות, התשמ&quot;א-1981, כולל תיקון 13. הפנייה
        היא בלשון רבים ומיועדת לכל המגדרים.
      </p>

      <H2>מי אחראי על המידע</H2>
      <p className="mt-2">
        המשתלה היא הבעלים של המידע שנאסף באתר והאחראית עליו. האתר פועל על פלטפורמת &quot;משתלות&quot;, שמספקת לנו את התשתית
        הטכנית ומעבדת את המידע בשמנו ולפי הוראותינו בלבד.
      </p>

      <H2>אילו פרטים אנחנו אוספים</H2>
      <p className="mt-2 font-medium text-gray-900">פרטים שאתם מוסרים לנו:</p>
      <List>
        <li>בהזמנה או בבקשת הצעת מחיר: שם, טלפון, דואר אלקטרוני, אופן המסירה, הערות להזמנה ואסמכתת תשלום אם הזנתם.</li>
        {p.delivery && <li>במשלוח עד הבית: כתובת למשלוח, עיר ומיקוד.</li>}
        {p.customerAccounts && <li>בחשבון לקוח: כתובת דואר אלקטרוני לכניסה, פרטים אישיים, ספר כתובות, מוצרים מועדפים והיסטוריית הזמנות.</li>}
        {p.loyalty && <li>במועדון הלקוחות: צבירה ומימוש של נקודות.</li>}
        {p.newsletter && <li>בהרשמה לדיוור: כתובת דואר אלקטרוני ומועד ההסכמה.</li>}
        <li>בפנייה בנושא נגישות: תיאור הבעיה ופרטי הקשר שבחרתם למסור.</li>
      </List>
      <p className="mt-3 font-medium text-gray-900">מידע שנאסף באופן אוטומטי:</p>
      <List>
        <li>כתובת IP, סוג הדפדפן והמכשיר, העמודים שבהם ביקרתם, מועד הביקור והאתר שממנו הגעתם.</li>
        <li>מידע שנאסף באמצעות עוגיות וכלים דומים, כמפורט בהמשך.</li>
      </List>
      <p className="mt-3">
        אין חובה חוקית למסור לנו מידע. עם זאת, בלי שם, טלפון ודואר אלקטרוני לא נוכל לטפל בהזמנה, ובלי כתובת לא נוכל לשלוח
        אותה. אנחנו לא שומרים פרטי כרטיס אשראי באתר.
      </p>

      <H2>למה אנחנו משתמשים במידע</H2>
      <List>
        <li>טיפול בהזמנה: אישור, הכנה, מסירה או משלוח, ועדכונים לגביה.</li>
        <li>שירות לקוחות ומענה לפניות, כולל פניות נגישות.</li>
        {p.customerAccounts && <li>ניהול החשבון האישי והצגת ההזמנות שלכם.</li>}
        {p.loyalty && <li>ניהול הנקודות וההטבות במועדון הלקוחות.</li>}
        <li>שליחת דיוור ומבצעים, רק אם הסכמתם לכך במפורש.</li>
        <li>הפקת סטטיסטיקות שימוש ושיפור האתר והשירות.</li>
        <li>הצגת פרסומות מותאמות ומדידת האפקטיביות שלהן, ברשתות חברתיות ובאתרים אחרים.</li>
        <li>אבטחת האתר, מניעת הונאות ושימוש לרעה.</li>
        <li>עמידה בחובות לפי דין, למשל רישומים חשבונאיים.</li>
      </List>

      <H2>עוגיות (Cookies) וכלי מדידה</H2>
      <p className="mt-2">
        עוגייה היא קובץ קטן שהאתר שומר בדפדפן שלכם. אנחנו משתמשים גם באחסון מקומי בדפדפן, שפועל באופן דומה. סוגי העוגיות באתר:
      </p>
      <List>
        <li>
          <strong className="text-gray-900">הכרחיות:</strong> שמירת סל הקניות, הגדרות תפריט הנגישות
          {p.customerAccounts ? ' וההתחברות לחשבון הלקוח' : ''}. בלעדיהן האתר לא יעבוד כראוי.
        </li>
        <li>
          <strong className="text-gray-900">מדידה וסטטיסטיקה:</strong> Google Analytics של חברת Google. הכלי אוסף מידע על אופן
          השימוש באתר, כמו עמודים שנצפו, משך הביקור ומקור ההגעה, ומציג לנו נתונים מסוכמים.
        </li>
        <li>
          <strong className="text-gray-900">שיווק ופרסום:</strong> הפיקסל של Meta (פייסבוק ואינסטגרם). הכלי מתעד פעולות באתר, כמו
          צפייה במוצר, הוספה לסל או ביצוע הזמנה, כדי להציג לכם פרסומות רלוונטיות ולמדוד את תוצאות הקמפיינים שלנו.
        </li>
      </List>
      <p className="mt-3">
        Google ו-Meta אוספות את המידע הזה בעצמן ומשתמשות בו גם לפי מדיניות הפרטיות שלהן. אפשר לחסום או למחוק עוגיות בהגדרות
        הדפדפן, אבל אז חלק מהאתר עלול לא לפעול. אפשר גם לחסום את Google Analytics בתוסף הרשמי של Google
        (tools.google.com/dlpage/gaoptout), ולנהל את הפרסומות של Meta בהגדרות הפרסומות בחשבון שלכם בפייסבוק או באינסטגרם.
      </p>

      <H2>למי אנחנו מעבירים מידע</H2>
      <p className="mt-2">אנחנו לא מוכרים את המידע שלכם. אנחנו מעבירים מידע רק במידה הנדרשת:</p>
      <List>
        <li>לספקי התשתית שמפעילים את האתר: פלטפורמת &quot;משתלות&quot; ונותני שירותי אחסון, שרתים ושליחת דואר אלקטרוני.</li>
        <li>ל-Google ול-Meta, באמצעות כלי המדידה והפרסום שתוארו למעלה.</li>
        {p.delivery && <li>לחברת השליחויות או לשליח: הפרטים הדרושים למסירת ההזמנה.</li>}
        <li>לספק התשלום שבחרתם, אם התשלום מתבצע דרכו.</li>
        <li>לרשויות, לפי דרישה על פי דין או צו שיפוטי, או כדי להגן על זכויותינו במקרה של מחלוקת.</li>
      </List>
      <p className="mt-3">
        חלק מספקי השירות שומרים מידע בשרתים מחוץ לישראל, למשל באיחוד האירופי ובארצות הברית. במקרים כאלה המידע מועבר לפי
        תקנות הגנת הפרטיות (העברת מידע אל מאגרי מידע שמחוץ לגבולות המדינה).
      </p>

      <H2>כמה זמן המידע נשמר</H2>
      <p className="mt-2">
        אנחנו שומרים מידע כל עוד הוא נחוץ למטרה שלשמה נאסף, או לתקופה שהחוק מחייב, למשל לצורך רישומים חשבונאיים. כשמוחקים
        פרטי לקוח, ההזמנות נשארות ברישומים שלנו בלי השם, הטלפון, הדואר האלקטרוני והכתובת.
      </p>

      <H2>הזכויות שלכם</H2>
      <List>
        <li>לעיין במידע שנשמר עליכם (סעיף 13 לחוק).</li>
        <li>לבקש לתקן מידע לא נכון או לא מעודכן, או למחוק אותו (סעיף 14 לחוק).</li>
        <li>להסיר את עצמכם מרשימת הדיוור בכל עת, בלי לתת סיבה.</li>
        <li>לבקש שלא נשתמש במידע שלכם לפנייה שיווקית.</li>
      </List>
      {p.customerAccounts && (
        <p className="mt-3">אם יש לכם חשבון לקוח, אפשר להוריד את כל המידע שלכם ולמחוק את החשבון בעצמכם באזור האישי באתר.</p>
      )}
      <p className="mt-3">
        לכל בקשה אחרת פנו אלינו בפרטים שבסוף העמוד. נשיב לכם תוך 30 יום. אם לא קיבלתם מענה מספק, אפשר לפנות לרשות להגנת הפרטיות.
      </p>

      <H2>אבטחת מידע</H2>
      <p className="mt-2">
        האתר מוצפן (HTTPS), הגישה למידע מוגבלת לבעלי הרשאה בלבד, ואנחנו נוקטים אמצעי אבטחה מקובלים. עם זאת, אין מערכת שמוגנת
        באופן מוחלט, ולכן איננו יכולים להבטיח הגנה מלאה מפני חדירה.
      </p>

      <H2>קטינים</H2>
      <p className="mt-2">האתר אינו מיועד לילדים מתחת לגיל 18 בלי הסכמה של הורה או אפוטרופוס.</p>

      <H2>שינויים במדיניות</H2>
      <p className="mt-2">אנחנו עשויים לעדכן את המדיניות מעת לעת. הנוסח המעודכן יפורסם בעמוד הזה, ותאריך העדכון יופיע בראשו.</p>

      <H2>יצירת קשר</H2>
      {contact.length > 0 ? (
        <>
          <p className="mt-2">לשאלות ובקשות בנושא פרטיות אפשר לפנות אל {p.name}:</p>
          <List>
            {contact.map((c) => (
              <li key={c}>{c}</li>
            ))}
          </List>
        </>
      ) : (
        <p className="mt-2">לשאלות ובקשות בנושא פרטיות אפשר לפנות אלינו דרך עמוד צור הקשר.</p>
      )}
    </article>
  );
}
